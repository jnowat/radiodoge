/// A transaction request from the Send tab.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TransactionRequest {
    /// Recipient Dogecoin address
    pub to_address: String,
    /// Amount in DOGE
    pub amount_doge: f64,
    /// Optional memo (sent in LoRa packet payload)
    pub memo: Option<String>,
    /// Sender's WIF private key (from generated wallet)
    pub from_private_key_wif: Option<String>,
    /// Network fee in DOGE. `None` pays the network-estimated rate (never below 0.01 DOGE per started kB).
    #[serde(default)]
    pub fee_doge: Option<f64>,
    /// Radio a signed transaction even if the same txid went out within
    /// `tx_reply::RESEND_GUARD_SECS` (the duplicate-broadcast guard).
    #[serde(default)]
    pub allow_resend: bool,
}

/// What `send_transaction` hands back to the UI.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SendOutcome {
    pub message: String,
    /// Txid of a signed transaction (absent for the legacy unsigned stub).
    pub txid: Option<String>,
    pub explorer_url: Option<String>,
    pub frames: usize,
}

/// An incoming LoRa packet captured by the receive loop.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct IncomingPacket {
    /// Unix timestamp (seconds)
    pub timestamp: u64,
    /// Source node address
    pub source: NodeAddress,
    /// Destination node address
    pub destination: NodeAddress,
    /// Command type byte
    pub command: u8,
    /// Raw payload as hex string
    pub payload_hex: String,
    /// Human-readable decoded content (if parseable)
    pub decoded: Option<String>,
    /// RSSI of this packet in dBm
    pub rssi: i16,
    /// v0.4.0 — Number of mesh hops this packet has been relayed (0 = heard
    /// directly from the source). Carried in the header flags byte's upper nibble.
    #[serde(default)]
    pub hops: u8,
    /// FW13+/FW14+ — SNR in dB the board heard this packet at, when it reported
    /// one (RECEIVED_ACK_SIGNAL, or an RX_SIGNAL frame ahead of a forwarded frame).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub snr: Option<i8>,
}

/// v0.3.6 — Board-is-source-of-truth: live state reported by the Heltec device
/// on CMD_GET_SETTINGS (0x22) response.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct BoardSettings {
    /// Node address as currently stored in the board's NVS flash
    pub node_address: NodeAddress,
    /// Whether the board is in gateway mode (persisted across power cycles)
    pub gateway_mode: bool,
    /// v0.3.7 — Whether the WiFi radio is enabled (persisted, default true)
    #[serde(default = "default_true")]
    pub wifi_enabled: bool,
}

fn default_true() -> bool {
    true
}

/// v0.3.7 — A recently heard mesh neighbor.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct NeighborEntry {
    /// The neighbor's node address
    pub address: NodeAddress,
    /// Last heard RSSI in dBm
    pub rssi: i16,
    /// Unix timestamp (seconds) of last heard packet
    pub last_seen: u64,
    /// Last position this node shared (`POS:` message), if any.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub position: Option<crate::geo::Position>,
    /// Unix seconds when `position` arrived.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub position_at: Option<u64>,
}

/// v0.3.6 — Transaction history entry (kept in app-local JSON, last 50 entries).
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TxHistoryEntry {
    /// Unix timestamp (seconds) when the TX was initiated
    pub timestamp: u64,
    /// Recipient Dogecoin address
    pub to_address: String,
    /// Amount in DOGE
    pub amount_doge: f64,
    /// Optional memo
    pub memo: Option<String>,
    /// TX status: "sent", "failed"
    pub status: String,
}

/// Information about a serial port visible to the OS.
///
/// Returned by `list_ports_with_info()` so the UI can display friendly names,
/// prioritise USB serial devices, and flag ports that match known Heltec/ESP32 adapters.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PortInfo {
    /// OS-level port name (e.g. "COM3" on Windows, "/dev/ttyUSB0" on Linux)
    pub name: String,
    /// True if this is a USB serial adapter (vs. a native COM/PCI port)
    pub is_usb: bool,
    /// USB manufacturer string, if reported by the adapter
    pub manufacturer: Option<String>,
    /// USB product string, if reported by the adapter (e.g. "CP2102 USB to UART Bridge")
    pub product: Option<String>,
    /// USB Vendor ID in decimal (Silicon Labs = 4292, Jiangsu Qinheng = 6790)
    pub vid: Option<u16>,
    /// USB Product ID in decimal
    pub pid: Option<u16>,
    /// Short human-readable label for display (e.g. "COM3 — CP2102 USB to UART Bridge")
    pub description: String,
    /// True if this port matches a USB VID/PID known to be used by Heltec / ESP32 boards
    pub is_likely_heltec: bool,
}

/// Connection status — emitted as a Tauri event.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", content = "message")]
pub enum ConnectionStatus {
    Disconnected,
    Connecting,
    Connected,
    Error(String),
}

/// Wrapper for connection status events to the frontend.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ConnectionStatusEvent {
    pub status: String,
    pub port: Option<String>,
    pub node_address: Option<NodeAddress>,
    pub message: Option<String>,
    /// Firmware version string reported by the Heltec device, e.g. "v1.2.3"
    pub firmware_version: Option<String>,
}

impl ConnectionStatusEvent {
    pub fn disconnected() -> Self {
        ConnectionStatusEvent {
            status: "disconnected".to_string(),
            port: None,
            node_address: None,
            message: None,
            firmware_version: None,
        }
    }

    pub fn connecting(port: &str) -> Self {
        ConnectionStatusEvent {
            status: "connecting".to_string(),
            port: Some(port.to_string()),
            node_address: None,
            message: None,
            firmware_version: None,
        }
    }

    pub fn connected(port: &str, addr: NodeAddress, firmware_version: Option<String>) -> Self {
        ConnectionStatusEvent {
            status: "connected".to_string(),
            port: Some(port.to_string()),
            node_address: Some(addr),
            message: None,
            firmware_version,
        }
    }

    pub fn reconnecting(port: &str) -> Self {
        ConnectionStatusEvent {
            status: "reconnecting".to_string(),
            port: Some(port.to_string()),
            node_address: None,
            message: None,
            firmware_version: None,
        }
    }

    pub fn error(msg: &str) -> Self {
        ConnectionStatusEvent {
            status: "error".to_string(),
            port: None,
            node_address: None,
            message: Some(msg.to_string()),
            firmware_version: None,
        }
    }
}

#[cfg(test)]
mod tests {
    //! These types are the IPC contract with the TypeScript front end
    //! (`radiodoge-gui/src/lib/types/index.ts`). A renamed field breaks the GUI
    //! silently at runtime, so pin the wire names here.
    use super::*;
    use serde_json::json;

    #[test]
    fn node_address_display_and_defaults() {
        assert_eq!(NodeAddress::new(10, 0, 2).to_display_string(), "10.0.2");
        assert_eq!(NodeAddress::default(), NodeAddress::default_local());
        assert_eq!(NodeAddress::broadcast().to_display_string(), "255.255.255");
    }

    #[test]
    fn transaction_request_accepts_minimal_gui_payload() {
        // Older front ends send neither feeDoge nor allowResend.
        let tx: TransactionRequest = serde_json::from_value(json!({
            "toAddress": "Dtest", "amountDoge": 1.5, "memo": null, "fromPrivateKeyWif": null
        }))
        .unwrap();
        assert_eq!(tx.amount_doge, 1.5);
        assert!(tx.fee_doge.is_none());
        assert!(!tx.allow_resend, "duplicate guard must be on unless asked");
    }

    #[test]
    fn transaction_request_reads_camel_case_options() {
        let tx: TransactionRequest = serde_json::from_value(json!({
            "toAddress": "Dtest", "amountDoge": 2.0, "feeDoge": 0.02, "allowResend": true
        }))
        .unwrap();
        assert_eq!(tx.fee_doge, Some(0.02));
        assert!(tx.allow_resend);
    }

    #[test]
    fn send_outcome_uses_camel_case() {
        let v = serde_json::to_value(SendOutcome {
            message: "ok".into(),
            txid: Some("ab".into()),
            explorer_url: Some("u".into()),
            frames: 3,
        })
        .unwrap();
        assert_eq!(v["explorerUrl"], "u");
        assert_eq!(v["frames"], 3);
    }

    #[test]
    fn lora_settings_round_trip() {
        let s = LoraSettings::default();
        let v = serde_json::to_value(&s).unwrap();
        assert_eq!(v["spreadingFactor"], 7);
        assert_eq!(v["nodeAddress"]["region"], 10);
        let back: LoraSettings = serde_json::from_value(v).unwrap();
        assert_eq!(back.coding_rate, "4/5");
    }

    #[test]
    fn connection_status_constructors() {
        let c = ConnectionStatusEvent::connected(
            "COM3",
            NodeAddress::default_local(),
            Some("FW12".into()),
        );
        assert_eq!(c.status, "connected");
        assert_eq!(c.port.as_deref(), Some("COM3"));
        assert_eq!(ConnectionStatusEvent::disconnected().status, "disconnected");
        assert!(ConnectionStatusEvent::error("boom")
            .message
            .unwrap()
            .contains("boom"));
    }
}
